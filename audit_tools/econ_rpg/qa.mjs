import { pathToFileURL } from 'node:url';
import { writeFileSync } from 'node:fs';
import scenario from './game/scenarios/housing-crisis.js';
import { validateScenario, createRun, availableChoices, decide, advance } from './game/engine.js';
export function enumerate(s = scenario) {
  validateScenario(s);
  const complete = [], nodes = new Set(), choices = new Set();
  function visit(run) {
    if (run.history.length > s.nodes.length) throw Error('Loop in reachable path');
    if (run.phase === 'ending') { complete.push(run); return; }
    nodes.add(run.nodeID);
    const options = availableChoices(s, run);
    if (!options.length) throw Error(`Dead end: ${run.nodeID}`);
    for (const choice of options) {
      choices.add(`${run.nodeID}.${choice.id}`);
      visit(advance(s, decide(s, run, choice.id)));
    }
  }
  visit(createRun(s, { runID: 'qa', startedAt: 0 }));
  return { complete, nodes: [...nodes], choices: [...choices],
    unreachableNodes: s.nodes.filter(n => !nodes.has(n.id)).map(n => n.id),
    unreachableEndings: s.endings.filter(e => !complete.some(r => r.endingID === e.id)).map(e => e.id) };
}
export function summarize(result, s = scenario) {
  const combinations = new Map();
  for (const run of result.complete) {
    const key = `${run.history[0].choiceID} / ${run.endingID}`;
    if (!combinations.has(key)) combinations.set(key, run);
  }
  return { paths: result.complete.length, nodes: result.nodes.length, choices: result.choices.length,
    decisionCounts: [...new Set(result.complete.map(r => r.history.length))],
    endings: Object.fromEntries(s.endings.map(e => [e.id, result.complete.filter(r => r.endingID === e.id).length])),
    unreachableNodes: result.unreachableNodes, unreachableEndings: result.unreachableEndings,
    representatives: [...combinations.entries()].map(([combination, run]) => ({ combination,
      choices: run.history.map(h => h.choiceID), labels: run.history.map(h => h.label), state: run.state })) };
}
export function manualGuide(result) {
  const branches = new Map();
  for (const run of result.complete) {
    // Distinguish initial intervention, allocation/support rule and supply policy.
    const key = [run.history[0].choiceID, run.history[1].choiceID, run.history[3].choiceID, run.endingID].join(' / ');
    if (!branches.has(key)) branches.set(key, run);
  }
  const lines = ['# Instructor QA paths', '', 'Generated by `node audit_tools/econ_rpg/qa.mjs --manual audit_tools/econ_rpg/QA-PATHS.md`.', '',
    `All ${result.complete.length} legal paths have six decisions. This checklist covers all ${branches.size} major branch/ending combinations: opening intervention × allocation/support rule × supply policy × ending. It is a coverage list, not a ranking of policies.`, '',
    'Use each row’s six choice IDs in order; the label key below maps IDs to the exact buttons. Reload once at a consequence and once at a decision. Check the debrief against what you observed. The 13 opening-policy/ending representatives printed by the default QA command are a shorter first pass.', '',
    '| # | Six choices in order | Expected ending |', '|---|---|---|'];
  [...branches.values()].forEach((run, i) => lines.push(`| ${i + 1} | ${run.history.map(h => h.choiceID).join(' → ')} | ${run.endingID} |`));
  lines.push('', '## Button label key', '');
  for (const node of scenario.nodes) {
    lines.push(`### ${node.title}`, '');
    for (const choice of node.choices) lines.push(`- \`${choice.id}\`: ${choice.label}`);
    lines.push('');
  }
  lines.push('## Ending key', '');
  scenario.endings.forEach(e => lines.push(`- \`${e.id}\`: ${e.title}`));
  lines.push('', '## Additional focused checks', '',
    '- Budget gate: assistance → expand → grants. At supply, the construction subsidy must be absent with an explanation. Replay bridge → target → phase; the subsidy must be available.',
    '- Maintenance severity: compare ceiling → registry → phase against assistance → target → phase. Covered rentals lose an extra quality step.',
    '- Ceiling interaction: compare ceiling → registry → inspect → reform → taper → access against ceiling → exempt → inspect → reform → taper → access. Exempting new leases changes the construction response and ending.',
    '- Construction subsidy: play a row containing subsidy. Relief from reserved homes must arrive at decision 6, not when the subsidy is committed.',
    '- Restart: cancel with Escape, then confirm. Replay after an ending. Both fresh runs must start at the original indicators and clear the old history.',
    '- Mobile and keyboard: read the entire debrief at 320px, open each path detail, Tab through choices, activate with Enter/Space, and check focus after transitions. Test with your screen reader and a real phone.',
    '- Economics review: check whether distributions, delayed supply effects, fiscal tradeoffs and ending priorities fit your course. Numerical steps are illustrative and must not be interpreted as estimates.', '');
  return lines.join('\n');
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const result = enumerate();
  console.log(JSON.stringify(summarize(result), null, 2));
  if (process.argv.includes('--all')) console.log(JSON.stringify(result.complete.map(r => ({ ending: r.endingID, transitions: r.history })), null, 2));
  const output = process.argv.indexOf('--write');
  if (output >= 0) writeFileSync(process.argv[output + 1], JSON.stringify({ summary: summarize(result), paths: result.complete }, null, 2));
  const manual = process.argv.indexOf('--manual');
  if (manual >= 0) writeFileSync(process.argv[manual + 1], manualGuide(result));
  if (result.unreachableNodes.length || result.unreachableEndings.length) process.exitCode = 1;
}
