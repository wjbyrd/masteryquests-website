import { pathToFileURL } from 'node:url';
import { writeFileSync } from 'node:fs';
import scenario from './game/scenarios/housing-crisis.js';
import { validateScenario, createRun, availableChoices, decide, advance } from './game/engine.js';
export function enumerate(s = scenario) {
  validateScenario(s);
  const complete = [], nodes = new Set(), choices = new Set();
  function visit(run) {
    if (run.history.length > s.nodes.length) throw Error('Loop in reachable path');
    if (run.phase === 'ending') { complete.push(run); return; }
    nodes.add(run.nodeID);
    const options = availableChoices(s, run);
    if (!options.length) throw Error(`Dead end: ${run.nodeID}`);
    for (const choice of options) {
      choices.add(`${run.nodeID}.${choice.id}`);
      visit(advance(s, decide(s, run, choice.id)));
    }
  }
  visit(createRun(s, { runID: 'qa', startedAt: 0 }));
  return { complete, nodes: [...nodes], choices: [...choices],
    unreachableNodes: s.nodes.filter(n => !nodes.has(n.id)).map(n => n.id),
    unreachableEndings: s.endings.filter(e => !complete.some(r => r.endingID === e.id)).map(e => e.id) };
}
export function summarize(result, s = scenario) {
  const combinations = new Map();
  for (const run of result.complete) {
    const key = `${run.history[0].choiceID} / ${run.endingID}`;
    if (!combinations.has(key)) combinations.set(key, run);
  }
  return { paths: result.complete.length, nodes: result.nodes.length, choices: result.choices.length,
    decisionCounts: [...new Set(result.complete.map(r => r.history.length))],
    endings: Object.fromEntries(s.endings.map(e => [e.id, result.complete.filter(r => r.endingID === e.id).length])),
    unreachableNodes: result.unreachableNodes, unreachableEndings: result.unreachableEndings,
    representatives: [...combinations.entries()].map(([combination, run]) => ({ combination,
      choices: run.history.map(h => h.choiceID), labels: run.history.map(h => h.label), state: run.state })) };
}
export function manualGuide(result) {
  const selected=[], covered=new Set();
  const features=run=>[`ending:${run.endingID}`,...run.history.map(h=>`${h.nodeID}.${h.choiceID}:${h.consequence}`)];
  for(const run of result.complete) if(features(run).some(f=>!covered.has(f))){selected.push(run);features(run).forEach(f=>covered.add(f));}
  const summary=summarize(result);
  const lines=['# Room to Stay — version 2 QA paths','','Generated by `node audit_tools/econ_rpg/qa.mjs --manual audit_tools/econ_rpg/QA-PATHS.md`.','',
    `All ${result.complete.length} legal paths begin after a binding rent ceiling has been imposed. Each has six decisions: allocation → maintenance → supply → distribution → mitigation → two-year review. Seven nodes and ${result.choices.length} node/choice pairs retain two distribution branches.`, '',
    `The ${selected.length} representative routes below cover every choice, reachable consequence variant and ending. They are coverage examples, not policy rankings.`, '',
    '| Ending | Paths |','|---|---|',...Object.entries(summary.endings).map(([id,count])=>`| ${id} | ${count} |`),'',
    '| # | Six choices in order | Expected ending |','|---|---|---|'];
  selected.forEach((run,i)=>lines.push(`| ${i+1} | ${run.history.map(h=>h.choiceID).join(' → ')} | ${run.endingID} |`));
  lines.push('','## Choice key','');
  for(const node of scenario.nodes){lines.push(`### ${node.title} (${node.id})`,'');for(const c of node.choices)lines.push(`- \`${c.id}\`: ${c.label}`);lines.push('');}
  lines.push('## Focused checks','',
    '- Opening: relief 5, availability 2, quality 5, budget 7, construction incentive 2. Both opening choices inherit the ceiling; exemption retains covered incumbent leases.',
    '- Lottery: allocation changes, but availability does not increase. Repair grants improve quality without adding units.',
    '- New-construction exemption is offered after a lottery, not after all new leases were already exempted. Incentives change now; units arrive only at decision 6.',
    '- Compare registry → grants → reform → search → taper → access with exempt → grants → reform → search → taper → access. The completed supply response is smaller when new units remain controlled.',
    '- Distribution branch: verify controlled versus exempt new-lease rent descriptions. Incumbent renewal protection improves security but reduces turnover opportunities.',
    '- Mitigation: assistance, temporary grants and tapering retain the ceiling. Transfers do not create apartments; aid can affect rents in exempt segments.',
    '- Save/resume works at every v2 phase. A v1 save displays the existing version-mismatch notice and cannot be silently reinterpreted as a v2 path.',
    '- Ending: check the initial-market ceiling diagram, Pe/Pc, Qs/Qe/Qd and shortage bracket. A lottery does not close Qd − Qs. Later exemptions are not presented as the initial graph.',
    '- All four additionality variants and four park pricing variants are exhaustively tested in instructional-followup.test.mjs and browser-tested via internal run IDs.',
    '- Keyboard: wrong answers permit correction; correct answers become natively disabled, focus moves to the explanation, and Tab reaches Next. Check replay, Return to Games, 200% zoom and 320px reflow.','');
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const result = enumerate();
  console.log(JSON.stringify(summarize(result), null, 2));
  if (process.argv.includes('--all')) console.log(JSON.stringify(result.complete.map(r => ({ ending: r.endingID, transitions: r.history })), null, 2));
  const output = process.argv.indexOf('--write');
  if (output >= 0) writeFileSync(process.argv[output + 1], JSON.stringify({ summary: summarize(result), paths: result.complete }, null, 2));
  const manual = process.argv.indexOf('--manual');
  if (manual >= 0) writeFileSync(process.argv[manual + 1], manualGuide(result));
  if (result.unreachableNodes.length || result.unreachableEndings.length) process.exitCode = 1;
}
