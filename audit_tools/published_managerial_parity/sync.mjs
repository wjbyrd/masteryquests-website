export const include='<script src="../local-telemetry.js"></script>\n';
const read=(root,p)=>fs.readFileSync(path.join(root,p),'utf8').replace(/\r\n/g,'\n');
export function localClient(root){
 const source=read(root,'play/managerial-directorate-telemetry-poc/telemetry-client.js');
 const between=(start,end)=>{const a=source.indexOf(start),b=source.indexOf(end,a);assert(a>=0&&b>a,`Source boundary changed: ${start}`);return source.slice(a,b);};
 const fn=name=>{const match=source.match(new RegExp('^  function '+name+'\\([^]*?^  }','m'));assert(match,`Missing maintained function ${name}`);return match[0];};
 const tracker=between('  // BEGIN GENERATED COMPOSER BEHAVIOR','  function readJSON(');
 const csv=['installLocalTelemetryColumns','installLocalCsvDownload','localTelemetryTail','attachLocalMeasurements'].map(fn).join('\n\n');
 let hooks=fn('installHooks');
 hooks=hooks.replace('mapGameEvent(data || {},measurements)','localEvent(data || {})').replace('    wrapAfter("showMasteryReportScreen", masterySummary);\n','    wrapAfter("showMasteryReportScreen", ()=>MQContract.resources());\n');
 const launch=hooks.indexOf('    // Capture ownership before launch helpers');assert(launch>0);hooks=hooks.slice(0,launch)+'  }';
 const completed=source.match(/  const COMPLETION_EVENTS = new Set\(\[[\s\S]*?\]\);/)[0];
 return `/* GENERATED by audit_tools/published_managerial_parity/sync.mjs.
 * Tracker, view accumulation, pre-verification snapshot, reset/readiness hooks and
 * CSV enrichment derive from the validated private adapter. No network transport,
 * anonymous identity, queue, private storage isolation or research event stream. */
(function managerialLocalTelemetry(){
  "use strict";
  if(window.__managerialLocalTelemetryInstalled)return;
  window.__managerialLocalTelemetryInstalled=true;
  const state={activeRunId:''};
${completed}
${tracker}
${fn('globalValue')}
  // Only the interval identity/readiness context needed by the shared lifecycle.
  function currentContext(raw={}){
    const q=globalValue('currentQuestion',null)||{},r=globalValue('remediationState',null)||{};
    const stage=String(raw.remediationStage ?? (r.active?r.stage:''));
    return {mode:String(raw.mode ?? globalValue('gameMode','standard')).replace(/-complete$/,''),
      position:Number(raw.room ?? globalValue('room',0)),
      questionId:String(raw.questionId ?? raw.question ?? q.id ?? q.questionId ?? ''),
      remediationStage:stage==='repair'?stage:'',bridgeStage:stage==='bridge'?stage:'',retestStage:stage==='retest'?stage:''};
  }
  // Shared lifecycle emits are intentionally inert here: the existing local
  // sendGameData remains the only row producer. No anonymous envelope is built.
  function emit(){}
  function pauseForLifecycle(){}
  function captureQuestionShown(){return beginInterval();}
  function localEvent(raw){
    if(raw.event==='start'||raw.event==='resume'){
      const localRun=String(raw.runID ?? globalValue('runID',''));
      if(raw.event==='start'||state.activeRunId!==localRun){
        tracker.complete();examViews.clear();intervalKey='';pendingTiming=null;shownToken='';
      }else{tracker.complete();pendingTiming=null;shownToken='';}
      state.activeRunId=localRun;runClosed=false;
    }else if(COMPLETION_EVENTS.has(raw.event)||/_(?:complete|bust|ended_by_student)$/.test(raw.event||'')){
      suspendQuestion('run-ended');runClosed=true;
    }
  }
${fn('wrapAfter')}
${fn('installExamHooks')}
${csv}
${hooks}
  installHooks();
  // Only the late exam-finalize wrapper is installed again after the UI adapter.
  document.addEventListener('DOMContentLoaded',()=>{try{installExamHooks();}catch(_){}});
  document.addEventListener('selectionchange',()=>safeBehavior(()=>{if(!globalValue('answerSubmissionPending',false))tracker.selection();}));
  document.addEventListener('copy',()=>safeBehavior(()=>{if(!globalValue('answerSubmissionPending',false))tracker.copy();}));
  window.addEventListener('blur',()=>safeBehavior(()=>{if(!globalValue('answerSubmissionPending',false))tracker.blur();}));
  window.addEventListener('focus',()=>safeBehavior(()=>{if(!globalValue('answerSubmissionPending',false))tracker.focus();}));
  document.addEventListener('visibilitychange',()=>safeBehavior(()=>tracker.visibility()));
})();
`;
}
export function sync(root,check=false){
 // The current Strategy Desk CSS/fallbacks refer to an underscore filename,
 // while the maintained artwork uses spaces. Preserve the artwork verbatim.
 const artwork=fs.readFileSync(path.join(root,publicRoot,'strategy-desk/question background image.webp'));
 const alias=path.join(root,publicRoot,'strategy-desk/question_background_image.webp');
 if(check)assert.deepEqual(fs.readFileSync(alias),artwork,'Strategy Desk artwork alias is stale');else fs.writeFileSync(alias,artwork);
 const generated=localClient(root),file=path.join(root,publicRoot,'local-telemetry.js');
 assert(!/fetch\(|sendBeacon|XMLHttpRequest|anonymousClientId|DEFAULT_ENDPOINT|QUEUE_KEY|CLIENT_KEY/.test(generated),'Public transport boundary');
 if(check)assert.equal(read(root,`${publicRoot}/local-telemetry.js`),generated,'Stale local client; run sync.mjs');else fs.writeFileSync(file,generated);
 for(const game of games){const file=path.join(root,publicRoot,game,'index.html'),html=fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n');const without=html.replaceAll(include,'');const anchor='<script src="../managerial-parity.js"></script>';assert.equal(without.split(anchor).length,2);const next=without.replace(anchor,include+anchor);if(check)assert.equal(html,next,`${game}: missing/duplicate public tracker include`);else if(html!==next)fs.writeFileSync(file,next);}
 console.log('PASS: public local telemetry derived from maintained private helpers; four script includes verified.');
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))sync(path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..'),process.argv.includes('--check'));
